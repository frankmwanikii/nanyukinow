/** Areas covered by Nanyuki Now listings. */
export const LOOK_LOCATIONS = ['Nanyuki', 'Timau', 'Naromoru'];

const AREA_COORDS = {
    Nanyuki: { lat: -0.0167, lng: 37.0728 },
    Timau: { lat: 0.082, lng: 37.239 },
    Naromoru: { lat: -0.163, lng: 37.017 },
};

function resolveLocation(item, index = 0) {
    if (LOOK_LOCATIONS.includes(item.location)) {
        return item.location;
    }
    if (LOOK_LOCATIONS.includes(item.area)) {
        return item.area;
    }

    const raw = `${item.location || ''} ${item.title || ''}`.toLowerCase();

    if (raw.includes('timau')) return 'Timau';
    if (
        raw.includes('naro moru') ||
        raw.includes('naromoru') ||
        raw.includes('naro-moru')
    ) {
        return 'Naromoru';
    }
    if (
        raw.includes('nanyuki') ||
        raw.includes('ol pejeta') ||
        raw.includes('solio') ||
        raw.includes('sirimon') ||
        raw.includes('laikipia') ||
        raw.includes('airfield') ||
        raw.includes('sportsman')
    ) {
        return 'Nanyuki';
    }

    return LOOK_LOCATIONS[index % LOOK_LOCATIONS.length];
}

function jitterCoord(base, index, spread = 0.018) {
    const offset = ((index % 7) - 3) * (spread / 3);
    return Number((base + offset).toFixed(5));
}

export function listingSlug(title, id) {
    const base = String(title || '')
        .toLowerCase()
        .normalize('NFKD')
        .replace(/[\u0300-\u036f]/g, '')
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/^-+|-+$/g, '')
        .replace(/-{2,}/g, '-');

    if (base) return base;
    return `listing-${id ?? 'unknown'}`;
}

/**
 * Deduplicated catalogue for the Explore page.
 * Home sections keep their own curated arrays above.
 */
export const allListings = (() => {
    const map = new Map();
    [...listings, ...trending, ...activities, ...wildlifeSafaris, ...airbnbs, ...recent, ...extras].forEach(
        (item) => {
            if (!map.has(String(item.id))) {
                map.set(String(item.id), item);
            }
        },
    );
    return Array.from(map.values());
})();

/** Unique slug map so duplicate titles get a stable -id suffix. */
const listingSlugById = (() => {
    const used = new Map();
    const byId = new Map();

    allListings.forEach((item) => {
        let slug = listingSlug(item.title, item.id);
        if (used.has(slug) && used.get(slug) !== String(item.id)) {
            slug = `${slug}-${item.id}`;
        }
        used.set(slug, String(item.id));
        byId.set(String(item.id), slug);
    });

    return byId;
})();

export function slugForListing(listing) {
    if (!listing) return 'listing';
    if (listing.slug) return listing.slug;
    return (
        listingSlugById.get(String(listing.id)) ||
        listingSlug(listing.title, listing.id)
    );
}

export function enrichListing(item, index = 0) {
    const phones = [
        '+254 700 112 334',
        '+254 722 445 668',
        '+254 733 901 220',
        '+254 711 556 890',
    ];
    const prices = ['$', '$$', '$$$'];
    const location = resolveLocation(item, index);
    const center = AREA_COORDS[location];
    const slug = item.slug || slugForListing(item);

    return {
        ...item,
        slug,
        location,
        area: location,
        lat: center
            ? jitterCoord(center.lat, index)
            : item.lat,
        lng: center
            ? jitterCoord(center.lng, index + 2, 0.022)
            : item.lng,
        isOpen: item.isOpen ?? index % 5 !== 3,
        phone: item.phone ?? phones[index % phones.length],
        tagline:
            item.tagline ??
            item.subcategory ??
            item.category ??
            'Local favourite',
        priceLevel: item.priceLevel ?? prices[index % prices.length],
        verified: item.verified ?? true,
        score:
            item.score ??
            (item.rating != null ? (item.rating * 2).toFixed(1) : null),
    };
}

/**
 * Handpicked Gold List for the home page.
 * Load more reveals the next batch of curated listings.
 */
export const goldList = (() => {
    const ranked = allListings
        .map((item, index) => enrichListing(item, index))
        .filter((item) => (item.rating ?? 0) >= 4.3 || item.badge === 'top')
        .sort((a, b) => (b.rating ?? 0) - (a.rating ?? 0));

    if (ranked.length >= 12) return ranked;

    const seen = new Set(ranked.map((item) => String(item.id)));
    const filler = allListings
        .map((item, index) => enrichListing(item, index))
        .filter((item) => !seen.has(String(item.id)));

    return [...ranked, ...filler];
})();

export function getListingById(id) {
    if (id == null || id === '') return null;
    const index = allListings.findIndex((item) => String(item.id) === String(id));
    if (index === -1) return null;
    return enrichListing(allListings[index], index);
}

/** Lookup by name slug (preferred) or legacy id. */
export function getListingBySlug(slugOrId) {
    if (slugOrId == null || slugOrId === '') return null;
    const key = String(slugOrId);

    const index = allListings.findIndex((item) => {
        const slug = item.slug || slugForListing(item);
        return slug === key;
    });
    if (index !== -1) {
        return enrichListing(allListings[index], index);
    }

    return getListingById(key);
}

export function listingHref(listing) {
    const slug = slugForListing(listing);
    return `/listings/${encodeURIComponent(slug)}`;
}

export function getRelatedListings(listing, relatedIds = [], limit = 3) {
    if (!listing) return [];
    const byId = new Map(
        allListings.map((item, index) => [
            String(item.id),
            enrichListing(item, index),
        ]),
    );
    const picked = [];
    const seen = new Set([String(listing.id)]);

    const sameSubcategory = (item) =>
        Boolean(listing.subcategory) &&
        item.subcategory === listing.subcategory;

    const sameCategory = (item) =>
        item.categoryKey === listing.categoryKey ||
        item.category === listing.category;

    const tryAdd = (item) => {
        if (!item || seen.has(String(item.id))) return false;
        picked.push(item);
        seen.add(String(item.id));
        return picked.length >= limit;
    };

    // 1) Explicit related IDs that match this subcategory / category
    for (const rid of relatedIds) {
        const item = byId.get(String(rid));
        if (!item) continue;
        if (sameSubcategory(item) || sameCategory(item)) {
            if (tryAdd(item)) return picked;
        }
    }

    // 2) Same subcategory (e.g. all Airbnbs)
    if (listing.subcategory) {
        for (const item of byId.values()) {
            if (sameSubcategory(item) && tryAdd(item)) return picked;
        }
    }

    // 3) Same category (e.g. all Stay)
    for (const item of byId.values()) {
        if (sameCategory(item) && tryAdd(item)) return picked;
    }

    return picked;
}

export function filterListings(
    items,
    {
        categoryKey = null,
        subcategory = null,
        query = '',
        location = null,
        minRating = 0,
        openNow = false,
    } = {},
) {
    const q = query.trim().toLowerCase();
    const area = location && location !== 'all' ? location : null;

    return items.filter((item) => {
        if (categoryKey && item.categoryKey !== categoryKey) return false;
        if (subcategory && item.subcategory !== subcategory) return false;
        if (minRating > 0 && (item.rating ?? 0) < minRating) return false;
        if (openNow && item.isOpen === false) return false;
        if (area && item.location !== area && item.area !== area) return false;

        if (!q) return true;

        const haystack = [
            item.title,
            item.location,
            item.area,
            item.category,
            item.subcategory,
            item.tagline,
        ]
            .filter(Boolean)
            .join(' ')
            .toLowerCase();

        return haystack.includes(q);
    });
}
